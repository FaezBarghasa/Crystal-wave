use std::panic::{catch_unwind, AssertUnwindSafe};
use crate::error::{LogicError, Result};
use crate::plugins::plugin_host::AudioPlugin;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PluginStatus {
    Active,
    Bypassed,
    Faulted(String),
}

/// Hardened FFI Plugin Slot with catch_unwind panic isolation and float sanitization
pub struct HardenedPluginSlot {
    pub slot_id: usize,
    pub plugin: Box<dyn AudioPlugin>,
    pub status: PluginStatus,
}

impl HardenedPluginSlot {
    pub fn new(slot_id: usize, plugin: Box<dyn AudioPlugin>) -> Self {
        Self {
            slot_id,
            plugin,
            status: PluginStatus::Active,
        }
    }

    pub fn safe_process(
        &mut self,
        left: &mut [f32],
        right: &mut [f32],
        sidechain: Option<&[f32]>,
    ) -> Result<()> {
        if matches!(self.status, PluginStatus::Bypassed | PluginStatus::Faulted(_)) {
            return Ok(());
        }

        let slot_id = self.slot_id;
        let plugin = AssertUnwindSafe(&mut self.plugin);

        let result = catch_unwind(move || {
            let plugin = plugin;
            plugin.process(left, right, sidechain);
        });

        match result {
            Ok(()) => {
                // Defensive sanitization: verify plugin didn't emit NaN or Inf
                for s in left.iter_mut().chain(right.iter_mut()) {
                    if !s.is_finite() {
                        *s = 0.0;
                        self.status =
                            PluginStatus::Faulted("Generated non-finite float (NaN/Inf)".into());
                        return Err(LogicError::DspError(
                            "Non-finite float generated by plugin".into(),
                        ));
                    }
                }
                Ok(())
            }
            Err(panic_err) => {
                let reason = if let Some(msg) = panic_err.downcast_ref::<&str>() {
                    msg.to_string()
                } else if let Some(msg) = panic_err.downcast_ref::<String>() {
                    msg.clone()
                } else {
                    "Unknown foreign panic".to_string()
                };
                self.status = PluginStatus::Faulted(reason.clone());
                Err(LogicError::PluginFfiPanic { slot_id, reason })
            }
        }
    }

    pub fn reset_fault(&mut self) {
        self.plugin.reset();
        self.status = PluginStatus::Active;
    }
}

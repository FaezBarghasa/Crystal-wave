    /// Instantiate audio engine for the given instrument type
    pub fn create_instrument(&self, sample_rate: f32) -> Box<dyn VirtualInstrument> {
        let mut synth = PolyphonicSynth::new(self.display_name(), 16, sample_rate);
        match self {
            BuiltInInstrumentType::Alchemy | BuiltInInstrumentType::ES2 => {
                synth.waveform = OscillatorWaveform::Sawtooth;
            }
            BuiltInInstrumentType::RetroSynth => {
                synth.waveform = OscillatorWaveform::Square;
            }
            BuiltInInstrumentType::VintageElectricPiano => {
                synth.waveform = OscillatorWaveform::Sine;
            }
            BuiltInInstrumentType::Sculpture => {
                synth.waveform = OscillatorWaveform::Triangle;
            }
            _ => {
                synth.waveform = OscillatorWaveform::Sawtooth;
            }
        }
        Box::new(synth)
    }
